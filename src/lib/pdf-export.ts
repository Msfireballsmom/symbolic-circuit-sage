// PDF Export utility for Circuit Sage solutions
export function exportSolutionAsPDF(
  title: string,
  steps: string[],
  results?: { label: string; value: string }[],
) {
  // Use browser print to generate PDF-quality output
  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    alert('Please allow popups to export PDF');
    return;
  }

  const resultsHTML = results
    ? `<div class="results">
        <h3>Results</h3>
        <table>
          <tr><th>Parameter</th><th>Value</th></tr>
          ${results.map(r => `<tr><td>${r.label}</td><td><code>${r.value}</code></td></tr>`).join('')}
        </table>
      </div>`
    : '';

  const stepsHTML = steps
    .map((step, i) => {
      if (step.match(/^(STEP \d|═{3,}|FINAL|───)/)) {
        return `<h3 class="step-header">${step.replace(/[═─]/g, '')}</h3>`;
      }
      return `<p class="step">${step}</p>`;
    })
    .join('');

  printWindow.document.write(`
    <!DOCTYPE html>
    <html>
    <head>
      <title>${title} — Circuit Sage</title>
      <style>
        * { margin: 0; padding: 0; box-sizing: border-box; }
        body { font-family: 'Times New Roman', serif; padding: 40px; color: #1a1a1a; line-height: 1.6; }
        h1 { font-size: 20px; margin-bottom: 4px; }
        h2 { font-size: 14px; color: #666; font-weight: normal; margin-bottom: 20px; }
        h3 { font-size: 14px; margin: 16px 0 8px; padding-top: 8px; border-top: 1px solid #ddd; }
        .step-header { font-weight: bold; color: #333; text-transform: uppercase; font-size: 12px; letter-spacing: 0.5px; }
        .step { font-family: 'Courier New', monospace; font-size: 11px; margin: 2px 0; padding: 2px 0; }
        .results { margin: 16px 0; }
        .results table { width: 100%; border-collapse: collapse; font-size: 12px; }
        .results th, .results td { text-align: left; padding: 4px 8px; border-bottom: 1px solid #eee; }
        .results th { font-weight: bold; background: #f5f5f5; }
        .results code { font-family: 'Courier New', monospace; font-weight: bold; }
        .footer { margin-top: 30px; padding-top: 10px; border-top: 2px solid #333; font-size: 10px; color: #999; text-align: center; }
        @media print { body { padding: 20px; } }
      </style>
    </head>
    <body>
      <h1>${title}</h1>
      <h2>Generated by Circuit Sage — ${new Date().toLocaleDateString()}</h2>
      ${resultsHTML}
      <div class="steps">
        <h3>Step-by-Step Solution</h3>
        ${stepsHTML}
      </div>
      <div class="footer">
        Circuit Sage — Verified with KCL/KVL power balance
      </div>
      <script>
        window.onload = () => { window.print(); };
      </script>
    </body>
    </html>
  `);
  printWindow.document.close();
}
